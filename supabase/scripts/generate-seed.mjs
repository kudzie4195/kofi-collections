#!/usr/bin/env node
// Generates the demo seed from the TypeScript demo seed so mock and Supabase
// modes always contain the same fictional records. Writes two files:
//
//   supabase/seed_auth.sql     the 8 demo auth.users + auth.identities rows
//                              (creates REAL, sign-in-able accounts)
//   supabase/seed_content.sql  everything else, all in schema `kofi`
//                              (needs seed_auth.sql to have run first)
//
//   node supabase/scripts/generate-seed.mjs
//
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadSeed, projectRoot } from './load-seed.mjs';

const { buildSeed, DEMO_IDENTITIES, DEMO_USERS, DEMO_UUIDS, DEMO_EMAILS, DEMO_PASSWORD } = await loadSeed();
const seed = buildSeed();

const U = (id) => {
  const v = DEMO_UUIDS[id];
  if (!v) throw new Error(`No fixed UUID for seed id "${id}" — add it to src/data/supabase/demo.ts`);
  return v;
};
const s = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === undefined || v === null ? 'null' : String(Number(v)));
const b = (v) => (v ? 'true' : 'false');
const ts = (v) => (v ? `${s(v)}::timestamptz` : 'null');
const arr = (list, type) => (list.length ? `array[${list.map(s).join(', ')}]::${type}[]` : `'{}'::${type}[]`);
const json = (v) => `${s(JSON.stringify(v))}::jsonb`;
const uuid = (id) => `${s(U(id))}::uuid`;
const uuidOrNull = (id) => (id ? uuid(id) : 'null');

const consentIds = {};
let consentN = 0;
for (const a of seed.artists) if (a.consentVersion) consentIds[a.id] = `c0000000-0000-4000-8000-${String(++consentN).padStart(12, '0')}`;

// ----------------------------------------------------------------- users ----
const userKeys = Object.values(DEMO_USERS);
const identityByUser = Object.fromEntries(DEMO_IDENTITIES.filter((d) => d.viewer.userId).map((d) => [d.viewer.userId, d]));
const artistByUser = Object.fromEntries(seed.artists.map((a) => [a.userId, a]));
const curatorByUser = Object.fromEntries(seed.curators.map((c) => [c.userId, c]));
function profileFor(userKey) {
  const ident = identityByUser[userKey];
  const role = artistByUser[userKey] ? 'artist' : curatorByUser[userKey] ? 'curator' : userKey === DEMO_USERS.admin ? 'admin' : 'public';
  const name = ident?.viewer.displayName ?? artistByUser[userKey]?.workingName ?? curatorByUser[userKey]?.name ?? userKey;
  return { role, name };
}

let lines = [];
const out = (l = '') => lines.push(l);
const header = (title, body) => {
  out('-- =============================================================================');
  out(`-- Kofi Collections — ${title} (FICTIONAL DATA ONLY)`);
  out('-- GENERATED by supabase/scripts/generate-seed.mjs from src/data/mock/seed.ts.');
  out('-- Do not edit by hand; edit the TS seed / src/data/supabase/demo.ts and regenerate.');
  out('--');
  for (const l of body) out(l ? `-- ${l}` : '--');
  out('-- =============================================================================');
  out();
};
function writeOut(name) {
  const target = path.join(projectRoot, 'supabase', name);
  writeFileSync(target, lines.join('\n') + '\n');
  console.log(`wrote ${path.relative(projectRoot, target)} (${lines.length} lines)`);
}

// ============================================================ seed_auth.sql ==
header('demo auth accounts', [
  '!!! CREATES REAL AUTH ACCOUNTS. Do not run this on a project with real users',
  '!!! unless you intend to: it inserts 8 rows into the SHARED auth.users table,',
  `!!! and every one of them can sign in with the published password ${DEMO_PASSWORD}.`,
  '',
  'auth.users is shared with every product on this Supabase project. Inserting',
  "into it fires EVERY trigger on auth.users: Kofi's kofi_on_auth_user_created",
  '(which creates the kofi.profiles rows) and any trigger the other product has',
  '(for example one that creates a public.profiles row per new user).',
  '',
  'Run order: migrations 0000-0007 → seed_auth.sql → seed_content.sql.',
  'Safe to re-run: existing ids / identities are left alone (on conflict do nothing).',
  '',
  'Remove these accounts again (cascades to auth.identities and the kofi',
  'profiles / artists / curators rows; also fires the other product\'s delete cascades):',
  `  delete from auth.users where id in (${userKeys.map((k) => `'${U(k)}'`).join(', ')});`,
  '',
  'Demo accounts:',
  ...userKeys.map((k) => `  ${U(k)}  ${DEMO_EMAILS[k]}  (${profileFor(k).role})`),
]);
out('begin;');
out();
for (const key of userKeys) {
  const { role, name } = profileFor(key);
  const email = DEMO_EMAILS[key];
  out(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)\n` +
      `values ('00000000-0000-0000-0000-000000000000', ${uuid(key)}, 'authenticated', 'authenticated', ${s(email)}, extensions.crypt(${s(DEMO_PASSWORD)}, extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}'::jsonb, ${json({ display_name: name, kofi_role: role === 'admin' ? 'public' : role })}, now(), now(), '', '', '', '')\n` +
      `on conflict (id) do nothing;`,
  );
  out(
    `insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)\n` +
      `values (${uuid(key)}, ${uuid(key)}, ${s(U(key))}, ${json({ sub: U(key), email, email_verified: true })}, 'email', now(), now(), now())\n` +
      `on conflict (provider_id, provider) do nothing;`,
  );
}
out();

out('commit;');
writeOut('seed_auth.sql');

// ========================================================= seed_content.sql ==
lines = [];
header('demo content', [
  'Everything here lives in schema `kofi`; nothing outside it is written.',
  'Requires supabase/seed_auth.sql to have run first (artists/curators reference',
  'the demo auth.users rows); it stops with an error if they are missing.',
  '',
  'Safe to re-run: content tables are restored by kofi.kofi_demo_reset(), which',
  'WIPES every row in the Kofi content tables (artists, artworks, images,',
  'institutions, curators, shortlists, inquiries, documents). Audit events and',
  'consents are append-only and are never deleted; seed rows for them are',
  'inserted once.',
  '',
  'The pristine snapshot kofi_demo_reset() restores from is kept in the',
  'kofi.demo_* tables (RLS on, no policies, no API grants).',
  '',
  'Mock id → UUID mapping',
  '  mock id              uuid                                   notes',
  ...Object.entries(DEMO_UUIDS).map(([k, v]) => `  ${k.padEnd(20)} ${v}   ${DEMO_EMAILS[k] ? `auth user ${DEMO_EMAILS[k]}` : ''}`.trimEnd()),
  ...Object.entries(consentIds).map(([artistId, cid]) => `  consent:${artistId.padEnd(12)} ${cid}   consents row`),
]);
out('begin;');
out();
out('-- ---------------------------------------------------- require demo users --');
out(`do $$
declare
  missing integer;
begin
  select count(*) into missing
  from unnest(array[${userKeys.map((k) => s(U(k))).join(', ')}]::uuid[]) as d (id)
  where not exists (select 1 from auth.users u where u.id = d.id);
  if missing > 0 then
    raise exception 'seed_content.sql: % of the ${userKeys.length} demo auth users are missing. Run supabase/seed_auth.sql first.', missing;
  end if;
end $$;`);
out();
const SNAP = ['profiles', 'institutions', 'artists', 'artworks', 'artwork_images', 'curators', 'shortlists', 'shortlist_items', 'inquiries', 'documents'];
out('-- ------------------------------------------------------ demo snapshot -----');
out(`drop table if exists ${SNAP.map((t) => `kofi.demo_${t}`).join(', ')};`);
out('create table kofi.demo_profiles (id uuid primary key, role kofi.role not null, display_name text not null);');
for (const t of SNAP.slice(1)) out(`create table kofi.demo_${t} (like kofi.${t} including defaults);`);
out('-- The snapshot is not part of the API: no grants, RLS on with no policies.');
for (const t of SNAP) {
  out(`revoke all on kofi.demo_${t} from public, anon, authenticated;`);
  out(`alter table kofi.demo_${t} enable row level security;`);
}
out();

out('insert into kofi.demo_profiles (id, role, display_name) values');
out(
  userKeys
    .map((key) => {
      const { role, name } = profileFor(key);
      return `  (${uuid(key)}, '${role}', ${s(name)})`;
    })
    .join(',\n') + ';',
);
out();

out('insert into kofi.demo_institutions (id, name, type, website, city, country, created_at, updated_at) values');
out(seed.institutions.map((i) => `  (${uuid(i.id)}, ${s(i.name)}, '${i.type}', ${s(i.website)}, ${s(i.city)}, ${s(i.country)}, '2026-07-01T12:00:00Z', '2026-07-01T12:00:00Z')`).join(',\n') + ';');
out();

out(`insert into kofi.demo_artists (id, user_id, working_name, legal_name, pronouns, bio, statement, region_city, region_region, region_country, region_precision, mediums, career_stage, experience_commissions, experience_public_art, experience_residencies, experience_institutional_shows, experience_years_practicing, availability_commissions, availability_sales, availability_exhibitions, links, contact_email, contact_phone, contact_studio_address, kofi_notes, visibility, status, consent_version, consent_accepted_at, avatar_color, created_at, updated_at) values`);
out(
  seed.artists
    .map(
      (a) =>
        `  (${uuid(a.id)}, ${uuid(a.userId)}, ${s(a.workingName)}, ${s(a.legalName)}, ${s(a.pronouns)}, ${s(a.bio)}, ${s(a.statement)}, ` +
        `${s(a.region.city)}, ${s(a.region.region)}, ${s(a.region.country)}, '${a.region.precision}', ${arr(a.mediums, 'kofi.medium')}, '${a.careerStage}', ` +
        `${b(a.experience.commissions)}, ${b(a.experience.publicArt)}, ${b(a.experience.residencies)}, ${b(a.experience.institutionalShows)}, ${n(a.experience.yearsPracticing)}, ` +
        `${b(a.availability.commissions)}, ${b(a.availability.sales)}, ${b(a.availability.exhibitions)}, ${json(a.links)}, ` +
        `${s(a.contact.email)}, ${s(a.contact.phone)}, ${s(a.contact.studioAddress)}, ${s(a.kofiNotes)}, '${a.visibility}', '${a.status}', ` +
        `${s(a.consentVersion)}, ${ts(a.consentAcceptedAt)}, ${s(a.avatarColor)}, ${ts(a.createdAt)}, ${ts(a.updatedAt)})`,
    )
    .join(',\n') + ';',
);
out();

out(`insert into kofi.demo_artworks (id, artist_id, title, year, medium, materials, height, width, depth, unit, description, status, rights_note, price_amount, price_currency, price_visibility, visibility, tags, reviewed_at, created_at, updated_at) values`);
out(
  seed.artworks
    .map(
      (w) =>
        `  (${uuid(w.id)}, ${uuid(w.artistId)}, ${s(w.title)}, ${w.year}, '${w.medium}', ${arr(w.materials, 'text')}, ` +
        `${n(w.dimensions.height)}, ${n(w.dimensions.width)}, ${n(w.dimensions.depth)}, '${w.dimensions.unit}', ${s(w.description)}, '${w.status}', ${s(w.rightsNote)}, ` +
        `${n(w.price?.amount)}, ${s(w.price?.currency)}, '${w.priceVisibility}', '${w.visibility}', ${arr(w.tags, 'text')}, ${ts(w.reviewedAt)}, ${ts(w.createdAt)}, ${ts(w.updatedAt)})`,
    )
    .join(',\n') + ';',
);
out();

out('-- Seed images are inline SVG placeholders (data: URLs), exactly as in mock mode.');
out('insert into kofi.demo_artwork_images (id, artwork_id, src, alt, is_primary, metadata_stripped, position, created_at) values');
out(
  seed.artworks
    .flatMap((w) =>
      w.images.map((im, i) => `  (${uuid(im.id)}, ${uuid(w.id)}, ${s(im.src)}, ${s(im.alt)}, ${b(im.isPrimary)}, ${b(im.metadataStripped)}, ${i}, ${ts(w.createdAt)})`),
    )
    .join(',\n') + ';',
);
out();

out('insert into kofi.demo_curators (id, user_id, name, title, institution_id, work_email, purpose, status, verification_note, verified_at, created_at, updated_at) values');
out(
  seed.curators
    .map(
      (c) =>
        `  (${uuid(c.id)}, ${uuid(c.userId)}, ${s(c.name)}, ${s(c.title)}, ${uuid(c.institutionId)}, ${s(c.workEmail)}, ${s(c.purpose)}, '${c.status}', ${s(c.verificationNote)}, ${ts(c.verifiedAt)}, ${ts(c.createdAt)}, ${ts(c.verifiedAt ?? c.createdAt)})`,
    )
    .join(',\n') + ';',
);
out();

out('insert into kofi.demo_shortlists (id, curator_id, name, created_at, updated_at) values');
out(seed.shortlists.map((l) => `  (${uuid(l.id)}, ${uuid(l.curatorId)}, ${s(l.name)}, ${ts(l.createdAt)}, ${ts(l.updatedAt)})`).join(',\n') + ';');
out('insert into kofi.demo_shortlist_items (shortlist_id, artwork_id, note, added_at) values');
out(seed.shortlists.flatMap((l) => l.items.map((it) => `  (${uuid(l.id)}, ${uuid(it.artworkId)}, ${s(it.note)}, ${ts(it.addedAt)})`)).join(',\n') + ';');
out();

out('insert into kofi.demo_inquiries (id, curator_id, artist_id, artwork_id, message, status, created_at, decided_at, decided_by, staff_note, updated_at) values');
out(
  seed.inquiries
    .map(
      (q) =>
        `  (${uuid(q.id)}, ${uuid(q.curatorId)}, ${uuid(q.artistId)}, ${uuidOrNull(q.artworkId)}, ${s(q.message)}, '${q.status}', ${ts(q.createdAt)}, ${ts(q.decidedAt)}, ${q.decidedBy ? s(U(q.decidedBy)) : 'null'}, ${s(q.staffNote)}, ${ts(q.decidedAt ?? q.createdAt)})`,
    )
    .join(',\n') + ';',
);
out();

out("-- file_ref is the object path inside the private 'vault' bucket. Upload the");
out('-- matching fictional files with: node supabase/scripts/upload-demo-vault.mjs');
out('insert into kofi.demo_documents (id, artist_id, artwork_id, type, title, custodian, date, file_ref, file_name, size_bytes, visibility, created_at) values');
out(
  seed.documents
    .map(
      (d) =>
        `  (${uuid(d.id)}, ${uuid(d.artistId)}, ${uuidOrNull(d.artworkId)}, '${d.type}', ${s(d.title)}, ${s(d.custodian)}, ${s(d.date)}, ${s(`${U(d.artistId)}/${U(d.id)}`)}, ${s(d.fileName)}, ${d.sizeBytes}, '${d.visibility}', ${ts(d.createdAt)})`,
    )
    .join(',\n') + ';',
);
out();

out('-- ------------------------------------------------------- reset function ---');
out(`create or replace function kofi.kofi_demo_reset() returns void
language plpgsql volatile security definer set search_path = kofi, public as $fn$
begin
  -- Kofi staff only through the API; the SQL editor / psql (no JWT) is trusted.
  if auth.uid() is not null and not kofi.is_admin() then
    raise exception 'Only Kofi staff can reset demo data in Supabase mode.' using errcode = '42501';
  end if;
  if auth.uid() is null and session_user = 'authenticator' then
    raise exception 'Only Kofi staff can reset demo data in Supabase mode.' using errcode = '42501';
  end if;
  -- Bulk restore is not a user action: suppress per-row audit triggers for this transaction.
  perform set_config('kofi.seeding', 'on', true);

  delete from kofi.shortlist_items;
  delete from kofi.shortlists;
  delete from kofi.inquiries;
  delete from kofi.documents;
  delete from kofi.artwork_images;
  delete from kofi.artworks;
  delete from kofi.curators;
  delete from kofi.institutions;
  delete from kofi.artists;

  insert into kofi.profiles (id, role, display_name)
    select p.id, p.role, p.display_name from kofi.demo_profiles p
    where exists (select 1 from auth.users u where u.id = p.id)
  on conflict (id) do update set role = excluded.role, display_name = excluded.display_name;

  insert into kofi.institutions select * from kofi.demo_institutions;
  insert into kofi.artists select * from kofi.demo_artists;
  insert into kofi.artworks select * from kofi.demo_artworks;
  insert into kofi.artwork_images select * from kofi.demo_artwork_images;
  insert into kofi.curators select * from kofi.demo_curators;
  insert into kofi.shortlists select * from kofi.demo_shortlists;
  insert into kofi.shortlist_items select * from kofi.demo_shortlist_items;
  insert into kofi.inquiries select * from kofi.demo_inquiries;
  insert into kofi.documents select * from kofi.demo_documents;

  perform set_config('kofi.seeding', 'off', true);
end $fn$;`);
out('revoke execute on function kofi.kofi_demo_reset() from public, anon;');
out('grant execute on function kofi.kofi_demo_reset() to authenticated;');
out();
out('select kofi.kofi_demo_reset();');
out();

out('-- ------------------------------------------- append-only seed history ------');
out('insert into kofi.consents (id, user_id, artist_id, version, accepted_at) values');
out(
  seed.artists
    .filter((a) => a.consentVersion)
    .map((a) => `  (${s(consentIds[a.id])}::uuid, ${uuid(a.userId)}, ${uuid(a.id)}, ${s(a.consentVersion)}, ${ts(a.consentAcceptedAt)})`)
    .join(',\n') + '\non conflict (id) do nothing;',
);
out();
const mapEntity = (id) => DEMO_UUIDS[id] ?? id;
out('insert into kofi.audit_events (id, actor_id, actor_role, actor_name, action, entity_type, entity_id, at, consent_version, meta) values');
out(
  seed.audit
    .map(
      (e) =>
        `  (${uuid(e.id)}, ${s(mapEntity(e.actorId))}, '${e.actorRole}', ${s(e.actorName)}, ${s(e.action)}, ${s(e.entityType)}, ${s(mapEntity(e.entityId))}, ${ts(e.at)}, ${s(e.consentVersion)}, ${e.meta ? json(e.meta) : 'null'})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
);
out();
out('commit;');
writeOut('seed_content.sql');
