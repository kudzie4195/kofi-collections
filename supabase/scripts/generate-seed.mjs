#!/usr/bin/env node
// Generates supabase/seed.sql from the TypeScript demo seed so mock and
// Supabase modes always contain the same fictional records.
//
//   node supabase/scripts/generate-seed.mjs
//
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { loadSeed, projectRoot } from './load-seed.mjs';

const { buildSeed, DEMO_IDENTITIES, DEMO_USERS, DEMO_UUIDS, DEMO_EMAILS, DEMO_PASSWORD } = await loadSeed();
const seed = buildSeed();

const U = (id) => {
  const v = DEMO_UUIDS[id];
  if (!v) throw new Error(`No fixed UUID for seed id "${id}" — add it to src/data/supabase/demo.ts`);
  return v;
};
const s = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === undefined || v === null ? 'null' : String(Number(v)));
const b = (v) => (v ? 'true' : 'false');
const ts = (v) => (v ? `${s(v)}::timestamptz` : 'null');
const arr = (list, type) => (list.length ? `array[${list.map(s).join(', ')}]::${type}[]` : `'{}'::${type}[]`);
const json = (v) => `${s(JSON.stringify(v))}::jsonb`;
const uuid = (id) => `${s(U(id))}::uuid`;
const uuidOrNull = (id) => (id ? uuid(id) : 'null');

const consentIds = {};
let consentN = 0;
for (const a of seed.artists) if (a.consentVersion) consentIds[a.id] = `c0000000-0000-4000-8000-${String(++consentN).padStart(12, '0')}`;

// ----------------------------------------------------------------- users ----
const userKeys = Object.values(DEMO_USERS);
const identityByUser = Object.fromEntries(DEMO_IDENTITIES.filter((d) => d.viewer.userId).map((d) => [d.viewer.userId, d]));
const artistByUser = Object.fromEntries(seed.artists.map((a) => [a.userId, a]));
const curatorByUser = Object.fromEntries(seed.curators.map((c) => [c.userId, c]));
function profileFor(userKey) {
  const ident = identityByUser[userKey];
  const role = artistByUser[userKey] ? 'artist' : curatorByUser[userKey] ? 'curator' : userKey === DEMO_USERS.admin ? 'admin' : 'public';
  const name = ident?.viewer.displayName ?? artistByUser[userKey]?.workingName ?? curatorByUser[userKey]?.name ?? userKey;
  return { role, name };
}

const lines = [];
const out = (l = '') => lines.push(l);

out('-- =============================================================================');
out('-- Kofi Collections — demo seed (FICTIONAL DATA ONLY)');
out('-- GENERATED by supabase/scripts/generate-seed.mjs from src/data/mock/seed.ts.');
out('-- Do not edit by hand; edit the TS seed / src/data/supabase/demo.ts and regenerate.');
out('--');
out('-- Run after the migrations (supabase db reset runs it automatically, or paste');
out('-- into the SQL editor). Safe to re-run: auth users are created once; content');
out('-- tables are restored by public.kofi_demo_reset(), which WIPES every row in the');
out('-- content tables (artists, artworks, images, institutions, curators,');
out('-- shortlists, inquiries, documents). Audit events and consents are append-only');
out('-- and are never deleted; seed rows for them are inserted once.');
out('--');
out(`-- Demo password for every demo account: ${DEMO_PASSWORD}`);
out('--');
out('-- Mock id → UUID mapping');
out('--   mock id              uuid                                   notes');
for (const [k, v] of Object.entries(DEMO_UUIDS)) {
  const email = DEMO_EMAILS[k] ? `auth user ${DEMO_EMAILS[k]}` : '';
  out(`--   ${k.padEnd(20)} ${v}   ${email}`.trimEnd());
}
for (const [artistId, cid] of Object.entries(consentIds)) out(`--   consent:${artistId.padEnd(12)} ${cid}   consents row`);
out('-- =============================================================================');
out();
out('begin;');
out();
out('-- ---------------------------------------------------------- auth users ----');
for (const key of userKeys) {
  const { role, name } = profileFor(key);
  const email = DEMO_EMAILS[key];
  out(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)\n` +
      `values ('00000000-0000-0000-0000-000000000000', ${uuid(key)}, 'authenticated', 'authenticated', ${s(email)}, extensions.crypt(${s(DEMO_PASSWORD)}, extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}'::jsonb, ${json({ display_name: name, role: role === 'admin' ? 'public' : role })}, now(), now(), '', '', '', '')\n` +
      `on conflict (id) do nothing;`,
  );
  out(
    `insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)\n` +
      `values (${uuid(key)}, ${uuid(key)}, ${s(U(key))}, ${json({ sub: U(key), email, email_verified: true })}, 'email', now(), now(), now())\n` +
      `on conflict (provider_id, provider) do nothing;`,
  );
}
out();

out('-- ------------------------------------------------------ demo snapshot -----');
out('create schema if not exists kofi_demo;');
out('revoke all on schema kofi_demo from public;');
out('drop table if exists kofi_demo.profiles, kofi_demo.institutions, kofi_demo.artists, kofi_demo.artworks, kofi_demo.artwork_images, kofi_demo.curators, kofi_demo.shortlists, kofi_demo.shortlist_items, kofi_demo.inquiries, kofi_demo.documents;');
out('create table kofi_demo.profiles (id uuid primary key, role public.role not null, display_name text not null);');
for (const t of ['institutions', 'artists', 'artworks', 'artwork_images', 'curators', 'shortlists', 'shortlist_items', 'inquiries', 'documents']) {
  out(`create table kofi_demo.${t} (like public.${t} including defaults);`);
}
out();

out('insert into kofi_demo.profiles (id, role, display_name) values');
out(
  userKeys
    .map((key) => {
      const { role, name } = profileFor(key);
      return `  (${uuid(key)}, '${role}', ${s(name)})`;
    })
    .join(',\n') + ';',
);
out();

out('insert into kofi_demo.institutions (id, name, type, website, city, country, created_at, updated_at) values');
out(seed.institutions.map((i) => `  (${uuid(i.id)}, ${s(i.name)}, '${i.type}', ${s(i.website)}, ${s(i.city)}, ${s(i.country)}, '2026-07-01T12:00:00Z', '2026-07-01T12:00:00Z')`).join(',\n') + ';');
out();

out(`insert into kofi_demo.artists (id, user_id, working_name, legal_name, pronouns, bio, statement, region_city, region_region, region_country, region_precision, mediums, career_stage, experience_commissions, experience_public_art, experience_residencies, experience_institutional_shows, experience_years_practicing, availability_commissions, availability_sales, availability_exhibitions, links, contact_email, contact_phone, contact_studio_address, kofi_notes, visibility, status, consent_version, consent_accepted_at, avatar_color, created_at, updated_at) values`);
out(
  seed.artists
    .map(
      (a) =>
        `  (${uuid(a.id)}, ${uuid(a.userId)}, ${s(a.workingName)}, ${s(a.legalName)}, ${s(a.pronouns)}, ${s(a.bio)}, ${s(a.statement)}, ` +
        `${s(a.region.city)}, ${s(a.region.region)}, ${s(a.region.country)}, '${a.region.precision}', ${arr(a.mediums, 'public.medium')}, '${a.careerStage}', ` +
        `${b(a.experience.commissions)}, ${b(a.experience.publicArt)}, ${b(a.experience.residencies)}, ${b(a.experience.institutionalShows)}, ${n(a.experience.yearsPracticing)}, ` +
        `${b(a.availability.commissions)}, ${b(a.availability.sales)}, ${b(a.availability.exhibitions)}, ${json(a.links)}, ` +
        `${s(a.contact.email)}, ${s(a.contact.phone)}, ${s(a.contact.studioAddress)}, ${s(a.kofiNotes)}, '${a.visibility}', '${a.status}', ` +
        `${s(a.consentVersion)}, ${ts(a.consentAcceptedAt)}, ${s(a.avatarColor)}, ${ts(a.createdAt)}, ${ts(a.updatedAt)})`,
    )
    .join(',\n') + ';',
);
out();

out(`insert into kofi_demo.artworks (id, artist_id, title, year, medium, materials, height, width, depth, unit, description, status, rights_note, price_amount, price_currency, price_visibility, visibility, tags, reviewed_at, created_at, updated_at) values`);
out(
  seed.artworks
    .map(
      (w) =>
        `  (${uuid(w.id)}, ${uuid(w.artistId)}, ${s(w.title)}, ${w.year}, '${w.medium}', ${arr(w.materials, 'text')}, ` +
        `${n(w.dimensions.height)}, ${n(w.dimensions.width)}, ${n(w.dimensions.depth)}, '${w.dimensions.unit}', ${s(w.description)}, '${w.status}', ${s(w.rightsNote)}, ` +
        `${n(w.price?.amount)}, ${s(w.price?.currency)}, '${w.priceVisibility}', '${w.visibility}', ${arr(w.tags, 'text')}, ${ts(w.reviewedAt)}, ${ts(w.createdAt)}, ${ts(w.updatedAt)})`,
    )
    .join(',\n') + ';',
);
out();

out('-- Seed images are inline SVG placeholders (data: URLs), exactly as in mock mode.');
out('insert into kofi_demo.artwork_images (id, artwork_id, src, alt, is_primary, metadata_stripped, position, created_at) values');
out(
  seed.artworks
    .flatMap((w) =>
      w.images.map((im, i) => `  (${uuid(im.id)}, ${uuid(w.id)}, ${s(im.src)}, ${s(im.alt)}, ${b(im.isPrimary)}, ${b(im.metadataStripped)}, ${i}, ${ts(w.createdAt)})`),
    )
    .join(',\n') + ';',
);
out();

out('insert into kofi_demo.curators (id, user_id, name, title, institution_id, work_email, purpose, status, verification_note, verified_at, created_at, updated_at) values');
out(
  seed.curators
    .map(
      (c) =>
        `  (${uuid(c.id)}, ${uuid(c.userId)}, ${s(c.name)}, ${s(c.title)}, ${uuid(c.institutionId)}, ${s(c.workEmail)}, ${s(c.purpose)}, '${c.status}', ${s(c.verificationNote)}, ${ts(c.verifiedAt)}, ${ts(c.createdAt)}, ${ts(c.verifiedAt ?? c.createdAt)})`,
    )
    .join(',\n') + ';',
);
out();

out('insert into kofi_demo.shortlists (id, curator_id, name, created_at, updated_at) values');
out(seed.shortlists.map((l) => `  (${uuid(l.id)}, ${uuid(l.curatorId)}, ${s(l.name)}, ${ts(l.createdAt)}, ${ts(l.updatedAt)})`).join(',\n') + ';');
out('insert into kofi_demo.shortlist_items (shortlist_id, artwork_id, note, added_at) values');
out(seed.shortlists.flatMap((l) => l.items.map((it) => `  (${uuid(l.id)}, ${uuid(it.artworkId)}, ${s(it.note)}, ${ts(it.addedAt)})`)).join(',\n') + ';');
out();

out('insert into kofi_demo.inquiries (id, curator_id, artist_id, artwork_id, message, status, created_at, decided_at, decided_by, staff_note, updated_at) values');
out(
  seed.inquiries
    .map(
      (q) =>
        `  (${uuid(q.id)}, ${uuid(q.curatorId)}, ${uuid(q.artistId)}, ${uuidOrNull(q.artworkId)}, ${s(q.message)}, '${q.status}', ${ts(q.createdAt)}, ${ts(q.decidedAt)}, ${q.decidedBy ? s(U(q.decidedBy)) : 'null'}, ${s(q.staffNote)}, ${ts(q.decidedAt ?? q.createdAt)})`,
    )
    .join(',\n') + ';',
);
out();

out("-- file_ref is the object path inside the private 'vault' bucket. Upload the");
out('-- matching fictional files with: node supabase/scripts/upload-demo-vault.mjs');
out('insert into kofi_demo.documents (id, artist_id, artwork_id, type, title, custodian, date, file_ref, file_name, size_bytes, visibility, created_at) values');
out(
  seed.documents
    .map(
      (d) =>
        `  (${uuid(d.id)}, ${uuid(d.artistId)}, ${uuidOrNull(d.artworkId)}, '${d.type}', ${s(d.title)}, ${s(d.custodian)}, ${s(d.date)}, ${s(`${U(d.artistId)}/${U(d.id)}`)}, ${s(d.fileName)}, ${d.sizeBytes}, '${d.visibility}', ${ts(d.createdAt)})`,
    )
    .join(',\n') + ';',
);
out();

out('-- ------------------------------------------------------- reset function ---');
out(`create or replace function public.kofi_demo_reset() returns void
language plpgsql volatile security definer set search_path = public as $fn$
begin
  -- Kofi staff only through the API; the SQL editor / psql (no JWT) is trusted.
  if auth.uid() is not null and not public.is_admin() then
    raise exception 'Only Kofi staff can reset demo data in Supabase mode.' using errcode = '42501';
  end if;
  if auth.uid() is null and session_user = 'authenticator' then
    raise exception 'Only Kofi staff can reset demo data in Supabase mode.' using errcode = '42501';
  end if;
  -- Bulk restore is not a user action: suppress per-row audit triggers for this transaction.
  perform set_config('kofi.seeding', 'on', true);

  delete from public.shortlist_items;
  delete from public.shortlists;
  delete from public.inquiries;
  delete from public.documents;
  delete from public.artwork_images;
  delete from public.artworks;
  delete from public.curators;
  delete from public.institutions;
  delete from public.artists;

  insert into public.profiles (id, role, display_name)
    select p.id, p.role, p.display_name from kofi_demo.profiles p
    where exists (select 1 from auth.users u where u.id = p.id)
  on conflict (id) do update set role = excluded.role, display_name = excluded.display_name;

  insert into public.institutions select * from kofi_demo.institutions;
  insert into public.artists select * from kofi_demo.artists;
  insert into public.artworks select * from kofi_demo.artworks;
  insert into public.artwork_images select * from kofi_demo.artwork_images;
  insert into public.curators select * from kofi_demo.curators;
  insert into public.shortlists select * from kofi_demo.shortlists;
  insert into public.shortlist_items select * from kofi_demo.shortlist_items;
  insert into public.inquiries select * from kofi_demo.inquiries;
  insert into public.documents select * from kofi_demo.documents;

  perform set_config('kofi.seeding', 'off', true);
end $fn$;`);
out('revoke execute on function public.kofi_demo_reset() from public, anon;');
out('grant execute on function public.kofi_demo_reset() to authenticated;');
out();
out('select public.kofi_demo_reset();');
out();

out('-- ------------------------------------------- append-only seed history ------');
out('insert into public.consents (id, user_id, artist_id, version, accepted_at) values');
out(
  seed.artists
    .filter((a) => a.consentVersion)
    .map((a) => `  (${s(consentIds[a.id])}::uuid, ${uuid(a.userId)}, ${uuid(a.id)}, ${s(a.consentVersion)}, ${ts(a.consentAcceptedAt)})`)
    .join(',\n') + '\non conflict (id) do nothing;',
);
out();
const mapEntity = (id) => DEMO_UUIDS[id] ?? id;
out('insert into public.audit_events (id, actor_id, actor_role, actor_name, action, entity_type, entity_id, at, consent_version, meta) values');
out(
  seed.audit
    .map(
      (e) =>
        `  (${uuid(e.id)}, ${s(mapEntity(e.actorId))}, '${e.actorRole}', ${s(e.actorName)}, ${s(e.action)}, ${s(e.entityType)}, ${s(mapEntity(e.entityId))}, ${ts(e.at)}, ${s(e.consentVersion)}, ${e.meta ? json(e.meta) : 'null'})`,
    )
    .join(',\n') + '\non conflict (id) do nothing;',
);
out();
out('commit;');

const target = path.join(projectRoot, 'supabase', 'seed.sql');
writeFileSync(target, lines.join('\n') + '\n');
console.log(`wrote ${path.relative(projectRoot, target)} (${lines.length} lines)`);
