#!/usr/bin/env node
// Splits supabase/migrations/0010_intake.sql into supabase/apply/0010_part{1..n}.sql
// for pasting into the SQL editor / execute_sql (each ≤ 25 KB, each its own
// transaction, runnable in order; the last part records the migration and
// reloads PostgREST). The migration file stays the single source of truth:
// re-run this after editing it.
//
//   node supabase/scripts/split-0010.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = readFileSync(path.join(root, 'supabase/migrations/0010_intake.sql'), 'utf8');
const LIMIT = 25 * 1024;

// Section headers the parts start at (the first part starts at the body's start).
const CUTS = [
  { at: '-- ------------------------------------------------------------------ RPCs ----', title: 'RPCs (ensure_my_artist, record_import, set_link_verification, log_audit), grants, records 0010_intake' },
];

const lines = src.split('\n');
const begin = lines.indexOf('begin;');
const commit = lines.lastIndexOf('commit;');
if (begin < 0 || commit < 0) throw new Error('0010: expected one begin; … commit; block');
const body = lines.slice(begin + 1, commit);
const idx = CUTS.map((c) => {
  const i = body.indexOf(c.at);
  if (i < 0) throw new Error(`0010: section marker not found: ${c.at}`);
  return i;
});
const bounds = [0, ...idx, body.length];
const titles = ['pure helpers, artists columns + CHECKs, audit vocabulary, links guard + audit triggers, artists_visible', ...CUTS.map((c) => c.title)];
const n = bounds.length - 1;

mkdirSync(path.join(root, 'supabase/apply'), { recursive: true });
for (let k = 0; k < n; k++) {
  const chunk = body.slice(bounds[k], bounds[k + 1]).join('\n').trim();
  const head = [
    '-- =============================================================================',
    `-- Kofi Collections — 0010_intake.sql, part ${k + 1} of ${n}: ${titles[k]}`,
    '-- GENERATED by supabase/scripts/split-0010.mjs from supabase/migrations/0010_intake.sql.',
    `-- Run parts 1 → ${n} in order, each on its own (one transaction each). Every part is`,
    '-- idempotent, so a failed part can simply be run again. Schema kofi only.',
    '-- Never run 0008 after this. Then apply/0010_live_patch.sql. See docs/SUPABASE.md §11.',
    '-- =============================================================================',
    '',
    'begin;',
    '',
  ];
  const tail = ['', 'commit;', ...(k === n - 1 ? ['', "notify pgrst, 'reload schema';"] : []), ''];
  const text = [...head, chunk, ...tail].join('\n');
  const size = Buffer.byteLength(text);
  if (size > LIMIT) throw new Error(`part ${k + 1} is ${size} bytes (> ${LIMIT}); add a cut`);
  const file = path.join(root, `supabase/apply/0010_part${k + 1}.sql`);
  writeFileSync(file, text);
  console.log(`wrote ${path.relative(root, file)} (${size} bytes)`);
}
