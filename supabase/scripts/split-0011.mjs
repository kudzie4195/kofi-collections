#!/usr/bin/env node
// Splits supabase/migrations/0011_taxonomy.sql into supabase/apply/0011_part{1..n}.sql for
// pasting into the SQL editor (each ≤ 25 KB, each its own transaction, runnable in order;
// the last part records the migration and reloads PostgREST). Parts start at the
// "-- @part <title>" lines in the migration (generate-taxonomy.mjs adds one per tag chunk).
// The migration file stays the single source of truth: re-run this after editing it.
//
//   node supabase/scripts/generate-taxonomy.mjs && node supabase/scripts/split-0011.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = readFileSync(path.join(root, 'supabase/migrations/0011_taxonomy.sql'), 'utf8');
const LIMIT = 25 * 1024;

const lines = src.split('\n');
const begin = lines.indexOf('begin;');
const commit = lines.lastIndexOf('commit;');
if (begin < 0 || commit < 0) throw new Error('0011: expected one begin; … commit; block');
const body = lines.slice(begin + 1, commit);
const starts = body.map((l, i) => (l.startsWith('-- @part ') ? i : -1)).filter((i) => i >= 0);
if (starts[0] !== 0 && body.slice(0, starts[0]).some((l) => l.trim())) throw new Error('0011: content before the first -- @part marker');
const n = starts.length;

mkdirSync(path.join(root, 'supabase/apply'), { recursive: true });
for (const f of readdirSync(path.join(root, 'supabase/apply'))) if (/^0011_part\d+\.sql$/.test(f)) unlinkSync(path.join(root, 'supabase/apply', f));
for (let k = 0; k < n; k++) {
  const title = body[starts[k]].slice('-- @part '.length).trim();
  const chunk = body.slice(starts[k] + 1, k + 1 < n ? starts[k + 1] : body.length).join('\n').trim();
  const head = [
    '-- =============================================================================',
    `-- Kofi Collections — 0011_taxonomy.sql, part ${k + 1} of ${n}: ${title}`,
    '-- GENERATED by supabase/scripts/split-0011.mjs from supabase/migrations/0011_taxonomy.sql.',
    `-- Run parts 1 → ${n} in order, each on its own (one transaction each). Every part is`,
    '-- idempotent, so a failed part can simply be run again. Schema kofi only.',
    '-- Needs 0010. Then apply/0011_live_patch.sql. See docs/SUPABASE.md §12.',
    '-- =============================================================================',
    '',
    'begin;',
    '',
  ];
  const tail = ['', 'commit;', ...(k === n - 1 ? ['', "notify pgrst, 'reload schema';"] : []), ''];
  const text = [...head, chunk, ...tail].join('\n');
  const size = Buffer.byteLength(text);
  if (size > LIMIT) throw new Error(`part ${k + 1} (${title}) is ${size} bytes (> ${LIMIT}); add a -- @part marker`);
  const file = path.join(root, `supabase/apply/0011_part${k + 1}.sql`);
  writeFileSync(file, text);
  console.log(`wrote ${path.relative(root, file)} (${size} bytes) — ${title}`);
}
