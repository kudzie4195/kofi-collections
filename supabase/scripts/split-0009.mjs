#!/usr/bin/env node
// Splits supabase/migrations/0009_sales.sql into supabase/apply/0009_part{1..n}.sql
// for pasting into the SQL editor / execute_sql (each ≤ 25 KB, each its own
// transaction, runnable in order; the last part records the migration and
// reloads PostgREST). The migration file stays the single source of truth:
// re-run this after editing it.
//
//   node supabase/scripts/split-0009.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = readFileSync(path.join(root, 'supabase/migrations/0009_sales.sql'), 'utf8');
const LIMIT = 25 * 1024;

// Section headers the parts start at (the first part starts at the body's start).
const CUTS = [
  { at: '-- -------------------------------------------------------- partner helpers ---', title: 'partner helpers, open_calls guard trigger, read helpers, views' },
  { at: '-- ------------------------------------------------------------------- RPCs ---', title: 'lot RPCs (save_lot, set_lot_status, record_sale, delete_lot) with their EXECUTE grants' },
  { at: '-- ------------------------------------------- RPCs: payouts, decisions, reports ---', title: 'set_payout_status, set_application_status, kofi_report with their EXECUTE grants' },
  { at: '-- ------------------------------------------------------------ privileges ----', title: 'table / view grants, RLS, storage policy, realtime, ledger' },
];

const lines = src.split('\n');
const begin = lines.indexOf('begin;');
const commit = lines.lastIndexOf('commit;');
if (begin < 0 || commit < 0) throw new Error('0009: expected one begin; … commit; block');
const body = lines.slice(begin + 1, commit);
const idx = CUTS.map((c) => {
  const i = body.indexOf(c.at);
  if (i < 0) throw new Error(`0009: section marker not found: ${c.at}`);
  return i;
});
const bounds = [0, ...idx, body.length];
const titles = ['prerequisites, enums, pure helpers, open_calls columns, lots + payouts tables, audit vocabulary', ...CUTS.map((c) => c.title)];
const n = bounds.length - 1;

mkdirSync(path.join(root, 'supabase/apply'), { recursive: true });
for (let k = 0; k < n; k++) {
  const chunk = body.slice(bounds[k], bounds[k + 1]).join('\n').trim();
  const head = [
    '-- =============================================================================',
    `-- Kofi Collections — 0009_sales.sql, part ${k + 1} of ${n}: ${titles[k]}`,
    '-- GENERATED by supabase/scripts/split-0009.mjs from supabase/migrations/0009_sales.sql.',
    `-- Run parts 1 → ${n} in order, each on its own (one transaction each). Every part is`,
    '-- idempotent, so a failed part can simply be run again. Schema kofi only, plus',
    `-- (part ${n}) the "kofi programme partner insert" storage policy and the`,
    '-- supabase_realtime additions. See docs/SUPABASE.md §10.',
    '-- =============================================================================',
    '',
    'begin;',
    '',
  ];
  const tail = ['', 'commit;', ...(k === n - 1 ? ['', "notify pgrst, 'reload schema';"] : []), ''];
  const text = [...head, chunk, ...tail].join('\n');
  const size = Buffer.byteLength(text);
  if (size > LIMIT) throw new Error(`part ${k + 1} is ${size} bytes (> ${LIMIT}); add a cut`);
  const file = path.join(root, `supabase/apply/0009_part${k + 1}.sql`);
  writeFileSync(file, text);
  console.log(`wrote ${path.relative(root, file)} (${size} bytes)`);
}
