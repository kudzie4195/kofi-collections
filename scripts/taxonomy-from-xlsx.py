#!/usr/bin/env python3
"""Generate src/domain/taxonomy.data.ts from Kofi's filter-taxonomy workbook.

Usage: python3 scripts/taxonomy-from-xlsx.py docs/source/<workbook>.xlsx
The workbook is the source of truth for labels, definitions and phases; the app
only adds the entries listed in APP_ADDITIONS (each explained in the output).
"""
import json, sys, re
import openpyxl

src = sys.argv[1]
wb = openpyxl.load_workbook(src, data_only=True)

def rows(sheet, header_match):
    ws = wb[sheet]
    out, header = [], None
    for r in ws.iter_rows(values_only=True):
        cells = ['' if c is None else str(c).strip() for c in r]
        if header is None:
            if cells[0] == header_match:
                header = cells
            continue
        if not any(cells):
            continue
        out.append(dict(zip(header, cells)))
    return out

cats = rows('FILTER CATEGORIES', 'Category')
tags = rows('TAG LIBRARY', 'Tag ID')
impact = {r['Tag ID']: r for r in rows('SOCIAL IMPACT', 'Social Impact Tag')}
fields = rows('FIELD SCHEMA', 'API Field / Key')
reqs = rows('DEV REQUIREMENTS', 'Priority')

phase = lambda p: {'MVP': 'mvp', 'Phase 2': 'phase2', 'Phase 3': 'phase3'}[p]
selectable = lambda s: s.strip().lower().startswith('yes')

# The app's own additions to Kofi's library (kept separate so Kofi can approve or drop them).
APP_ADDITIONS = [
    {'id': 'medium.performance', 'category': 'medium', 'label': 'Performance', 'definition': 'Live or time-based work (added by the app: existing demo works use it).', 'artistSelectable': True, 'phase': 'mvp', 'appAddition': True},
    {'id': 'medium.video', 'category': 'medium', 'label': 'Video', 'definition': 'Moving image shown on a screen (added by the app; Kofi’s list has Film).', 'artistSelectable': True, 'phase': 'mvp', 'appAddition': True},
]

categories = []
for c in cats:
    categories.append({
        'id': c['Category ID'],
        'label': c['Category'],
        'ui': c['Recommended UI'],
        'source': c['Data Source / Type'],
        'belongsTo': c['Data Belongs To'],
        'phase': phase(c['Release Phase']),
        'note': c['Developer Notes'],
    })

library = []
for t in tags:
    tid = t['Tag ID']
    d = t['Definition / Purpose']
    if tid in impact:
        d = impact[tid]['Working Definition']
    library.append({
        'id': tid,
        'category': t['Category ID'],
        'label': t['Display Label'],
        'definition': d,
        'artistSelectable': selectable(t['Artist Selectable']),
        'phase': phase(t['Release Phase']),
    })
library += APP_ADDITIONS

ids = [t['id'] for t in library]
assert len(ids) == len(set(ids)), 'duplicate tag ids'
assert all(re.fullmatch(r'[a-z_]+\.[a-z0-9_]+', i) for i in ids), 'bad id shape'
cat_ids = {c['id'] for c in categories}
assert all(t['category'] in cat_ids for t in library), 'tag with unknown category'

def ts(v):
    return json.dumps(v, ensure_ascii=False, indent=2)

out = f"""/* GENERATED by scripts/taxonomy-from-xlsx.py from {src.split('/')[-1]} — do not edit by hand.
 * Kofi's workbook is the source of truth for labels, definitions and release phases.
 * The only hand-written part is APP_ADDITIONS in the script (tags the app needed that the
 * workbook does not list), each marked appAddition: true so Kofi can approve or drop them.
 */
export type TaxonomyPhase = 'mvp' | 'phase2' | 'phase3';

export interface TagCategoryDef {{
  id: string;
  label: string;
  ui: string;
  source: string;
  belongsTo: string;
  phase: TaxonomyPhase;
  note: string;
}}

export interface TagDef {{
  id: string;
  category: string;
  label: string;
  definition: string;
  artistSelectable: boolean;
  phase: TaxonomyPhase;
  appAddition?: boolean;
}}

export const TAG_CATEGORY_DEFS: readonly TagCategoryDef[] = {ts(categories)} as const;

export const TAG_LIBRARY: readonly TagDef[] = {ts(library)} as const;

/** Social Impact boundary, verbatim from the workbook. */
export const SOCIAL_IMPACT_BOUNDARY = {json.dumps(next(iter(impact.values()))['Important Boundary'])};
export const SOCIAL_IMPACT_NOTE = {json.dumps('Artist-selected subject and intent, not an automatic measure of positive impact')};

/** Workbook acceptance tests (DEV REQUIREMENTS), kept so the test suite can cite them. */
export const WORKBOOK_REQUIREMENTS: readonly {{ priority: string; phase: TaxonomyPhase; feature: string; behavior: string; test: string }}[] = {ts([{ 'priority': r['Priority'], 'phase': phase(r['Release Phase']), 'feature': r['Feature'], 'behavior': r['Required Behavior'], 'test': r['Acceptance Test'] } for r in reqs])} as const;
"""
open('src/domain/taxonomy.data.ts', 'w').write(out)
print(f"categories {len(categories)}, tags {len(library)} ({len(tags)} from the workbook + {len(APP_ADDITIONS)} app additions), requirements {len(reqs)}, fields {len(fields)}")
